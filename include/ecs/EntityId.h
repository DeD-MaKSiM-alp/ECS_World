#pragma once /* Защита от двойного включения */

/* Подключение переносимых типов данных */
#include <cstdint>

/* Подключение функциональных типов */
#include <functional>

/* Идентификатор сущности: 0 — невалидный; новые id только через World::createEntity(). */
struct EntityId
{
    /* Поле для хранения значения идентификатора */
    std::uint32_t value = 0;

    /*
    -static - показывает, что метод доступен без создания объекта класса
    -constexpr - показывает, что метод является константным, определяется при компиляции и может быть вызван в любом месте кода
    -noexcept - показывает, что метод не выбрасывает исключений
    -return EntityId{0} - возвращает значение типа EntityId с значением 0
    Функция нужна для того, чтобы можно было сравнивать идентификаторы и определять, является ли идентификатор невалидным.
    */
    static constexpr EntityId invalid() noexcept 
    { 
        return EntityId{0}; 
    }

    /*
    -operator== - специальная функция для переопределения оператора ==
    -constexpr - показывает, что метод является константным, определяется при компиляции и может быть вызван в любом месте кода
    -noexcept - показывает, что метод не выбрасывает исключений
    -return value == o.value - возвращает true, если значения идентификаторов равны
    Функция нужна для того, чтобы можно было сравнивать идентификаторы и определять, являются ли они равными.
    */
    constexpr bool operator==(EntityId o) const noexcept 
    { 
        return value == o.value; 
    }

    /*
    -operator!= - специальная функция для переопределения оператора !=
    -constexpr - показывает, что метод является константным, определяется при компиляции и может быть вызван в любом месте кода
    -noexcept - показывает, что метод не выбрасывает исключений
    -return value != o.value - возвращает true, если значения идентификаторов не равны
    Функция нужна для того, чтобы можно было сравнивать идентификаторы и определять, являются ли они неравными.
    */
    constexpr bool operator!=(EntityId o) const noexcept 
    { 
        return value != o.value; 
    }
};

/*
Нужно для того, чтобы можно было использовать как ключ в контейнере unordered_map и unordered_set
-template<> - делаем специальную версию шаблона для конкретного типа
-struct hash<EntityId> - Это специальная версия std::hash именно для EntityId.
-operator() - специальная функция для переопределения оператора ()
-const noexcept - показывает, что метод не выбрасывает исключений
-{} - создаем объект функции hash для std::uint32_t
-(e.value) - Здесь временный объект сразу вызывается как функция
-e.value - Берём внутреннее число из EntityId
-return std::hash<std::uint32_t>{}(e.value); - Возвращаем хеш значения идентификатора
Функция нужна для того, чтобы можно было использовать как ключ в контейнере unordered_map и unordered_set
Хэш - это число, которое вычисляется из значения, чтобы это значение можно было быстро искать в контейнерах вроде unordered_map
*/
namespace std
{
template<>
struct hash<EntityId>
{
    std::size_t operator()(EntityId e) const noexcept
    {
        return std::hash<std::uint32_t>{}(e.value);
    }
};
} // namespace std
