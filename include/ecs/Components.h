#pragma once

#include "EntityId.h"

#include <cstdint>

/* Данные компонентов — только простые данные; логика — в системах и World. */

/* Позиция на дискретной сетке; Grid хранит индекс по этим координатам. */
struct Position
{
    std::int32_t x = 0;
    std::int32_t y = 0;
};

/*
  Направление движения (заглушка ввода/AI до коммита 7).
  dx — изменение по X, dy — изменение по Y.
*/
struct Velocity
{
    std::int8_t dx = 0;
    std::int8_t dy = 0;
};

/* Уровень голода. Растёт каждый тик (HungerSystem). При достижении порога AI ищет еду. */
struct Hunger
{
    int value = 0;
};

/* Маркер: эта сущность является едой. Нет полей — сам факт наличия компонента важен. */
struct Food {};

/*
  Компонент проходимости.
  Используется для описания рельефа/тайла в клетке:
  - true  => клетка считается проходимой по этому объекту;
  - false => клетка считается непроходимой.
*/
struct Walkable
{
    bool value = true;
};

/*
  Маркер: сущность занимает клетку и не пускает других.
  World::moveEntity проверяет наличие этого компонента в целевой клетке.
*/
struct Blocking {};

/* Цель движения: координаты клетки, к которой нужно идти. Выставляет AISystem или Game. */
struct MoveTarget
{
    std::int32_t x = 0;
    std::int32_t y = 0;
};

/*
  Цель взаимодействия: id сущности, с которой нужно взаимодействовать (например, съесть еду).
  Выставляет AISystem, исполняет InteractionSystem.
*/
struct InteractTarget
{
    EntityId target{};
};

/* Маркер: сущность управляется игроком. AISystem пропускает таких сущностей. */
struct PlayerControlled {};
